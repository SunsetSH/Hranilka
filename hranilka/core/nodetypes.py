"""Константы типов узлов дерева.

Единый источник истины вместо строковых литералов "folder"/"service"/"account",
разбросанных по UI и слою данных. Значения совпадают с историческими литералами —
формат node["type"] в дереве и стеше не меняется.
"""

FOLDER = "folder"
SERVICE = "service"
ACCOUNT = "account"
CARD = "card"
WALLET = "wallet"

# Листовые узлы: открываются карточкой, поддерживают корзину, избранное, DnD.
LEAF_TYPES = frozenset({ACCOUNT, CARD, WALLET})

# Финансовые листья (fin_items): карточка строится из дескриптора типа.
# Новые типы добавляются сюда — вся листовая механика (корзина, избранное, DnD,
# поиск, точечное обновление) работает generic-ом.
FIN_LEAF_TYPES = frozenset({CARD, WALLET})


def is_fin_node(node_type) -> bool:
    """Узел дерева — финансовый лист (card/wallet). Единый предикат вместо
    трёх независимых определений (bulk.py/export.py — «всё, что не
    folder/service/account», tree.py/tree_ops.py — членство в FIN_LEAF_TYPES):
    расхождение конвенций делало добавление нового НЕ-фин типа узла риском —
    экспорт/bulk молча посчитали бы его финансовым, а удаление — аккаунтом.
    Узлы дерева всегда несут только распознанные типы (get_tree_structure
    отсеивает записи item_type вне реестра ДО попадания в дерево — см.
    tree_ops._build_fin_node), поэтому проверка членством эквивалентна
    исключению контейнеров/аккаунта, но не расползается по модулям."""
    return node_type in FIN_LEAF_TYPES
