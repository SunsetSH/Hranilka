"""Реестр горячих клавиш (шорткатов) — единый источник правды для привязки
в главном окне ([main.py]) и для вкладки «Шорткаты» в настройках ([dialogs.py]).

Модуль не зависит от Qt — это чистые данные плюс хелпер, накладывающий
пользовательские переопределения из config['shortcuts'] поверх дефолтов."""

# (id, подпись, сочетание по умолчанию, категория)
SHORTCUT_DEFS = [
    ("add_account",     "Добавить аккаунт",            "Ctrl+N",        "Создание"),
    ("add_service",     "Добавить сервис",             "Alt+N",         "Создание"),
    ("add_folder",      "Добавить папку",              "Ctrl+Shift+N",  "Создание"),
    ("edit_account",    "Редактировать аккаунт",       "Ctrl+E",        "Редактирование"),
    ("save_account",    "Сохранить аккаунт",           "Ctrl+S",        "Редактирование"),
    ("cancel_edit",     "Отменить редактирование",     "Esc",           "Редактирование"),
    ("gen_password",    "Сгенерировать пароль",        "Ctrl+G",        "Редактирование"),
    ("gen_personal",    "Сгенерировать ПД",            "Ctrl+D",        "Редактирование"),
    ("delete_selected", "Удалить выбранное в дереве",  "Del",           "Навигация"),
    ("focus_search",    "Перейти к поиску",            "Ctrl+F",        "Навигация"),
    ("toggle_expand",   "Свернуть/раскрыть дерево",    "Ctrl+T",        "Навигация"),
    ("open_settings",   "Открыть настройки",           "F1",            "Прочее"),
    ("open_bin",        "Открыть корзину",             "Ctrl+R",        "Прочее"),
    ("export_all",      "Экспортировать всё",          "Alt+E",         "Прочее"),
]

# Порядок категорий для отображения в UI
CATEGORIES = ["Создание", "Редактирование", "Навигация", "Прочее"]

LABELS = {sid: label for sid, label, _seq, _cat in SHORTCUT_DEFS}
DEFAULTS = {sid: seq for sid, _label, seq, _cat in SHORTCUT_DEFS}


def effective(config) -> dict:
    """DEFAULTS, поверх которых наложены пользовательские из config['shortcuts'].

    Возврат — {action_id: "Ctrl+X"} для всех известных действий. Если в будущем
    в SHORTCUT_DEFS добавится новое действие, у старых конфигов оно
    автоматически получит дефолт. Пустая строка означает «сочетание снято»."""
    mapping = dict(DEFAULTS)
    user = config.get("shortcuts", {}) or {}
    for sid, seq in user.items():
        if sid in mapping:          # игнорируем устаревшие/неизвестные ключи
            mapping[sid] = seq
    return mapping
