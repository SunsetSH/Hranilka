"""Исключение слоя данных: CorruptedPayloadError (файл-на-класс)."""


class CorruptedPayloadError(Exception):
    """JSON-payload сущности (servers.data и аналогичные колонки) не парсится —
    отличаем от отсутствующего/пустого payload ('{}'/NULL), который является
    легитимным пустым состоянием (M-03).

    Само содержимое повреждённой строки НЕ попадает в текст исключения/лог —
    там могут быть потенциально восстановимые секреты (пароли, приватные
    ключи). Вызыватель обязан открыть карточку в режиме fail-closed (без
    возможности сохранить поверх повреждённых данных) вместо того, чтобы
    молча подставить пустой словарь: обычное сохранение такой "пустой"
    карточки необратимо стёрло бы исходную (потенциально восстановимую)
    строку в БД."""

    def __init__(self, record_id: int) -> None:
        self.record_id = record_id
        super().__init__(
            f"Payload записи id={record_id} повреждён (невалидный JSON)")
